#!/usr/bin/env node
/**
 * Codegen for SQL migrations. Reads every `*.sql` under
 * `src/main/db/migrations/` and emits `src/main/db/migrations.gen.ts`
 * with the contents inlined as a `Record<string, string>`.
 *
 * Why not `import.meta.glob`? It's a vite runtime feature that adds an
 * implicit dependency on the bundler and makes the SQL set invisible
 * to TypeScript. Codegen makes the migration list explicit and
 * grep-able from any tool.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const SRC_DIR = join(ROOT, 'src', 'main', 'db', 'migrations');
const OUT_PATH = join(ROOT, 'src', 'main', 'db', 'migrations.gen.ts');

const files = readdirSync(SRC_DIR)
  .filter((f) => f.endsWith('.sql'))
  .sort();

if (files.length === 0) {
  console.error('No migrations found at', SRC_DIR);
  process.exit(1);
}

const entries = files.map((f) => {
  const sql = readFileSync(join(SRC_DIR, f), 'utf8');
  return { name: f, sql };
});

const banner = `/**
 * AUTO-GENERATED — do not edit by hand.
 *
 * Regenerated by \`scripts/build-migrations.mjs\` (runs as the \`gen:migrations\`
 * npm script and as part of the \`build\` / \`dev\` lifecycle). The migration
 * runner imports from this file rather than walking the filesystem at
 * runtime.
 */
`;

const tsLiteralEntries = entries
  .map((e) => `  ${JSON.stringify(e.name)}: ${JSON.stringify(e.sql)},`)
  .join('\n');

const out = `${banner}
export const MIGRATION_FILES: Readonly<Record<string, string>> = Object.freeze({
${tsLiteralEntries}
});
`;

writeFileSync(OUT_PATH, out, 'utf8');
console.log(`[migrations] wrote ${entries.length} migration(s) → ${OUT_PATH}`);
